import type { Handle } from '@sveltejs/kit/hooks';
import { config } from '#lib/server/config.js';
import { log } from '#lib/server/logger.js';
import { appInfo, httpRequestsTotal, httpRequestDuration, activeRequests } from '#lib/server/metrics.js';
import { closeRabbit, initRabbitMQ } from '#lib/server/rabbitmq.js';
import { closeValkey, initValkey } from '#lib/server/valkey.js';
import { closeCnpg, initCnpg } from '#lib/server/cnpg.js';
import { initDefectDojo } from '#lib/server/defectdojo.js';
import { initSmtp } from '#lib/server/smtp.js';
import '#lib/server/checks.js';
import { startSnapshots } from '#lib/server/snapshot.js';

// --- Initialization (runs once on server start) ---

let initialized = false;

async function init() {
	if (initialized) return;
	initialized = true;

	log('info', 'EpochCloud SvelteKit starting', {
		version: config.version,
		commit: config.commit,
		environment: config.environment,
		hostname: config.hostname,
		consumerMode: config.consumerMode,
		// Logged verbatim, scheme included: the scheme is what selects the OTLP
		// exporter's transport credentials, so it is the first thing to check
		// when spans stop arriving.
		otelEndpoint: config.otelEndpoint
	});

	// Set app info gauge
	appInfo.set(
		{
			version: config.version,
			commit: config.commit,
			build_time: config.buildTime,
			environment: config.environment
		},
		1
	);

	// Initialize service connections
	await initRabbitMQ();
	await initValkey();
	await initCnpg();
	void initDefectDojo();
	initSmtp();
	if (!config.consumerMode) startSnapshots();

	// Close the clients when the adapter announces shutdown.
	process.on('sveltekit:shutdown', async () => {
		await Promise.allSettled([closeRabbit(), closeValkey(), closeCnpg()]);
	});

	// The consumer subscribes inside connect(), on the first connection and on
	// every reconnect.
	if (config.consumerMode) {
		log('info', 'Consumer mode active - only /health and /metrics routes available');
	}
}

// Route paths that become metric labels. Anything else is "/other", so an
// unknown path never creates a new series.
const METRIC_PATHS = [
	'/',
	'/health',
	'/version',
	'/robots.txt',
	'/chaos',
	'/email/send',
	'/ntfy/send',
	'/ntfy/topic',
	'/cache/get',
	'/cache/set',
	'/rabbitmq/publish',
	'/rabbitmq/consume',
	'/cnpg/items',
	'/cnpg/items/delete',
	'/knative/invoke',
	'/features/all',
	'/features/evaluate',
	'/prometheus/increment',
	'/auth/session',
	'/api/faro/collect'
];

function metricPath(pathname: string): string {
	if (pathname.startsWith('/status/')) return '/status/:name';
	return METRIC_PATHS.includes(pathname) ? pathname : '/other';
}

// Response headers every route carries (OWASP HTTP Headers Cheat Sheet). The
// Content-Security-Policy, with frame-ancestors, is generated by SvelteKit from
// the csp option in vite.config.ts so its nonces match the page's own scripts.
const SECURITY_HEADERS: Record<string, string> = {
	'Referrer-Policy': 'strict-origin-when-cross-origin',
	'Permissions-Policy': 'camera=(), microphone=(), geolocation=(), payment=(), usb=()',
	'X-Content-Type-Options': 'nosniff'
};

function withSecurityHeaders(response: Response): Response {
	try {
		for (const [name, value] of Object.entries(SECURITY_HEADERS)) response.headers.set(name, value);
		return response;
	} catch {
		// Static file responses carry immutable headers: copy them.
		const headers = new Headers(response.headers);
		for (const [name, value] of Object.entries(SECURITY_HEADERS)) headers.set(name, value);
		return new Response(response.body, { status: response.status, statusText: response.statusText, headers });
	}
}

// Routes allowed in consumer mode
const consumerAllowedPaths = new Set(['/health', '/metrics']);

export const handle: Handle = async ({ event, resolve }) => {
	await init();

	const { pathname } = event.url;

	// Skip metrics tracking for the /metrics endpoint itself
	if (pathname === '/metrics') {
		return resolve(event);
	}

	// Consumer mode: block all routes except /health and /metrics
	if (config.consumerMode && !consumerAllowedPaths.has(pathname)) {
		return new Response('Consumer mode - only /health and /metrics available', { status: 404 });
	}

	const start = performance.now();
	const path = metricPath(pathname);
	const method = event.request.method;

	activeRequests.inc();

	try {
		const response = await resolve(event, {
			transformPageChunk: ({ html }) => {
				// Inject Rybbit analytics script via first-party proxy (/_a/ path)
				// to bypass ad blockers that block "analytics.*" domains.
				// The /_a/ prefix is rewritten to /api/ by Traefik middleware
				// and forwarded to the Rybbit backend. Same-origin requests
				// are indistinguishable from regular app traffic.
				if (config.rybbit.enabled) {
					html = html.replace('</head>', `<script src="/_a/script.js" data-site-id="${config.rybbit.siteId}" defer></script></head>`);
				}
				// Inject Faro config meta tag for client-side SDK initialization
				if (config.faro.enabled) {
					html = html.replace(
						'</head>',
						`<meta name="faro-config" content='${JSON.stringify({ enabled: true, version: config.version, environment: config.environment })}' /></head>`
					);
				}
				return html;
			}
		});
		const durationMs = performance.now() - start;
		const durationS = durationMs / 1000;

		httpRequestsTotal.inc({ method, path, status: String(response.status) });
		httpRequestDuration.observe({ method, path }, durationS);
		activeRequests.dec();

		log('info', 'request', {
			method,
			path,
			status: response.status,
			duration_seconds: Math.round(durationS * 1000) / 1000
		});

		return withSecurityHeaders(response);
	} catch (err) {
		activeRequests.dec();
		httpRequestsTotal.inc({ method, path, status: '500' });
		log('error', 'request error', { method, path, error: String(err) });
		throw err;
	}
};
